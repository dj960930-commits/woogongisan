"""Bundle the tiny scheduled Worker without npm dependencies or credentials."""
from pathlib import Path
import json
from datetime import datetime

ROOT=Path(__file__).resolve().parents[1]


def main():
    calendar=json.loads((ROOT/'android/app/src/main/assets/market-calendar.json').read_text(encoding='utf-8'))
    rows=[[int(datetime.fromisoformat(row['close']).timestamp()*1000),row['date']] for row in calendar['sessions']]
    assert rows and all(a[0]<b[0] for a,b in zip(rows,rows[1:]))
    data='export const coverageEnd='+json.dumps(calendar['end'])+';\nexport const sessions='+json.dumps(rows,separators=(',',':'))+';\n'
    source=ROOT/'workers/close-scheduler'
    (source/'calendar.mjs').write_text('// Generated by tools/build_free_scheduler.py\n'+data,encoding='utf-8')
    worker=(source/'worker.mjs').read_text(encoding='utf-8')
    bundle=worker.replace("import {sessions, coverageEnd} from './calendar.mjs';",data.replace('export const','const'))
    target=ROOT/'release/free-scheduler-worker.mjs';target.parent.mkdir(exist_ok=True)
    target.write_text(bundle,encoding='utf-8')
    print('Calendar sessions:',len(rows),'Dashboard bundle bytes:',target.stat().st_size)


if __name__=='__main__':main()
